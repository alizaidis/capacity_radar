def normalize_cpu_series(series: str | None) -> str | None:
    """Case-insensitive lookup for CPU series name (e.g. 'c4a' or 'C4a' -> 'C4A')."""
    if not series:
        return None
    target = series.strip().upper()
    if target in CPU_SERIES:
        return target
    return None


def get_cpu_zones_for_series(series: str) -> list[str]:
    """Return supported zones for a CPU series."""
    key = normalize_cpu_series(series)
    if not key:
        return []
    return list(CPU_SERIES[key]["zones"])


def get_cpu_regions_for_series(series: str) -> list[str]:
    """Return sorted supported regions for a CPU series."""
    zones = get_cpu_zones_for_series(series)
    return sorted({z.rsplit("-", 1)[0] for z in zones})


def get_cpu_candidate_shapes(
    series: str,
    shape_class: str = "any",
    target_vcpus: int = 64,
    min_vcpus_per_vm: int | None = None,
    max_vcpus_per_vm: int | None = None,
) -> list[dict]:
    """Return candidate CPU machine shapes ordered for high-density bin-packing.

    Prefers larger practical node shapes first (e.g. 64 -> 48 -> 32 -> 16 -> 8 -> 4 vCPUs)
    so deployments minimize per-VM overhead, then steps down to smaller shapes to harvest
    fragmented host capacity when large contiguous slots are stocked out.
    """
    key = normalize_cpu_series(series)
    if not key:
        return []
    sinfo = CPU_SERIES[key]
    sc = (shape_class or "any").strip().lower()
    # When shape_class is "any", prefer standard then highcpu (avoiding 8GB/vCPU highmem
    # premium unless no standard/highcpu shape exists at that vCPU count).
    class_pref = {"standard": 0, "highcpu": 1, "highmem": 2}

    raw = []
    for mt_name, spec in sinfo["shapes"].items():
        if sc != "any" and spec["shape_class"] != sc:
            continue
        v = spec["vcpus"]
        if min_vcpus_per_vm is not None and v < min_vcpus_per_vm:
            continue
        if max_vcpus_per_vm is not None and v > max_vcpus_per_vm:
            continue
        raw.append({
            "machine_type": mt_name,
            "vcpus": v,
            "memory_gb": spec["memory_gb"],
            "shape_class": spec["shape_class"],
            "series": key,
        })

    if not raw and sc != "any":
        # Fallback to all shape classes in series if requested class does not exist (e.g. T2A/H3 only have standard)
        return get_cpu_candidate_shapes(key, "any", target_vcpus, min_vcpus_per_vm, max_vcpus_per_vm)

    if sc == "any":
        # Keep one preferred shape per vCPU size (standard first, then highcpu, then highmem)
        best_by_vcpu: dict[int, dict] = {}
        for item in sorted(raw, key=lambda x: class_pref.get(x["shape_class"], 9)):
            best_by_vcpu.setdefault(item["vcpus"], item)
        candidates = list(best_by_vcpu.values())
    else:
        candidates = raw

    # Avoid tiny 1-2 vCPU shapes for large pools (>= 16 vCPUs) unless no >= 4 vCPU shape exists
    if target_vcpus >= 16 and min_vcpus_per_vm is None:
        filtered = [c for c in candidates if c["vcpus"] >= 4]
        if filtered:
            candidates = filtered

    # Partition into shapes <= target_vcpus (descending) followed by smallest shape > target_vcpus
    le_target = sorted([c for c in candidates if c["vcpus"] <= max(target_vcpus, 1)], key=lambda x: -x["vcpus"])
    gt_target = sorted([c for c in candidates if c["vcpus"] > max(target_vcpus, 1)], key=lambda x: x["vcpus"])

    # Cap default top shape at <= 96 vCPUs for reasonable cluster granularity unless pool is huge (>= 384)
    if target_vcpus < 384 and le_target:
        reasonable = [c for c in le_target if c["vcpus"] <= 96]
        huge = [c for c in le_target if c["vcpus"] > 96]
        le_target = reasonable + huge

    ordered = le_target + (gt_target[:1] if not le_target else [])
    return ordered if ordered else sorted(candidates, key=lambda x: x["vcpus"])


def compute_pool_chunk_bounds(
    remaining_vcpus: int,
    min_cluster_vcpus: int,
    shape_vcpus: int,
    placement_scope: str = "multi_region",
) -> tuple[int, int]:
    """Compute (min_vms, max_vms) for a single zone allocation attempt.

    Guarantees two invariants:
      1. Every created local cluster has >= min_cluster_vcpus (`min_vms * shape_vcpus >= min_cluster_vcpus`).
      2. Never leaves a sub-minimum tail remainder unintentionally: if `remaining_vcpus < min_cluster_vcpus`,
         requests at least `min_cluster_vcpus` so the final shard also satisfies the local cluster floor.
    """
    v = max(1, shape_vcpus)
    floor_vcpus = max(1, min_cluster_vcpus)
    if placement_scope == "single_zone":
        req_vcpus = max(remaining_vcpus, floor_vcpus)
        vms = max(1, math.ceil(req_vcpus / v))
        return vms, vms

    effective_target_vcpus = max(remaining_vcpus, floor_vcpus)
    min_vms = max(1, math.ceil(floor_vcpus / v))
    max_vms = max(min_vms, math.ceil(effective_target_vcpus / v))
    return min_vms, max_vms
